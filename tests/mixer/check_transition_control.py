"""NVIDIA integration: switcher-style control of the one transition on air.

The rules (Grass Valley Kayenne style, one A/B transition, nothing captured):
  * CUT during a transition completes it at the next frame boundary.
  * AUTO (fade) again for the scene on air pauses a crossfade, both sources moving; again resumes it.
  * Another scene during a transition replaces the preset picture; the transition continues to it.
  * A wipe ignores AUTO for its own scene; mixer.interrupt cuts back to the program.

Each case checks rendered pixels: which scene is on air (frame codes from frame_codes.py), that
program keeps moving (no frozen picture) and that the old program never returns after the command.
Supply source-0.mp4 and source-1.mp4 generated by frame_codes.py at 60 fps and a wipe clip with
alpha. Standalone graph on the local GPU; it never touches a running demo.
"""
import argparse
import hashlib
import json
import random
import socket
import threading
import time
from fractions import Fraction
from pathlib import Path

import numpy as np

from frame_codes import read_code

FADE = 1.2
# A command reaches the pixels within the pipeline delay: a few 60 fps ticks.
LANDING_S = 0.3
WIPE_CANCELLED = ('recovery_wipe', 'NodeGroup', 'Error while changing state: Another start of the group requested')


def identity(image):
    """('full0' | 'full1' | 'split' | None, frame number) of a rendered program picture."""
    code = read_code(image)
    if code:
        return f'full{code[0]}', code[1]
    left, right = read_code(image[:, :320]), read_code(image[:, 320:])
    if left and right and (left[0], right[0]) == (0, 1):
        return 'split', left[1]
    return None, None


def longest_still_run(digests):
    """Most consecutive identical pictures (by digest): a frozen program shows as a long run."""
    longest = run = 1 if digests else 0
    for previous, current in zip(digests, digests[1:]):
        run = run + 1 if previous == current else 1
        longest = max(longest, run)
    return longest


class Recorder:
    """Drains the assertion output on its own thread for the whole run, so commands can be
    issued meanwhile and no frame waits in the edge. Keeps per frame only what the checks need:
    arrival time, scene identity, frame number and a digest of the picture; plus the latest picture."""

    def __init__(self, output):
        self.output, self.frames, self.latest = output, [], None
        self._stop, self._thread, self._last_pts = threading.Event(), None, None

    def __enter__(self):
        self._thread = threading.Thread(target=self._run, daemon=True)
        self._thread.start()
        return self

    def __exit__(self, *exc):
        self._stop.set()
        self._thread.join(timeout=2)

    def _run(self):
        while not self._stop.is_set():
            try:
                frame = self.output.get(50)
            except ValueError as error:
                if str(error) == 'get: timeout':
                    continue
                raise
            pts = Fraction(frame.pts.timestamp * frame.pts.timebase.num, frame.pts.timebase.den)
            assert self._last_pts is None or pts >= self._last_pts, ('output pts went backwards', self._last_pts, pts)
            self._last_pts = pts
            image = np.frombuffer(frame.data[0], np.uint8).reshape(360, frame.linesize[0])[:, :640].copy()
            name, number = identity(image)
            self.frames.append((time.monotonic(), name, number, hashlib.blake2b(image.tobytes(), digest_size=16).digest()))
            self.latest = image

    def since(self, t):
        return [frame for frame in self.frames if frame[0] >= t]


def check(avp, mixer, rec, errors, control_port, wipe_file, wipe_seconds, spam_seed):
    avp.setReady()   # the control server greets clients only once the graph is ready
    channel = socket.create_connection(('127.0.0.1', control_port), timeout=5).makefile('rwb', buffering=0)
    assert channel.readline().startswith(b'100 ')

    def command(line):
        channel.write(line.encode() + b'\n')
        reply = channel.readline()
        assert reply.startswith((b'200 ', b'201 ')), (line, reply)
        if reply.startswith(b'200 '):
            return None
        body = []
        while (part := channel.readline()) not in (b'\n', b'\r\n'):
            assert part, 'control closed'
            body.append(part)
        return json.loads(b''.join(body))

    def status():
        return command('mixer.status recovery')

    def take(kind, scene, duration=None):
        if kind == 'cut':
            mixer.cut(scene)
        elif kind == 'fade':
            mixer.fade(scene, duration_sec=duration or FADE)
        elif kind == 'wipe':
            mixer.wipe(scene, wipe_file, duration_sec=wipe_seconds)
        elif kind == 'preview':
            mixer.preview(scene)
        elif kind == 'interrupt':
            avp.executeCommandsFromString('mixer.interrupt {"mixer":"recovery"}')
        return time.monotonic()

    def check_errors(allow_wipe_cancel=False):
        if allow_wipe_cancel:
            errors[:] = [error for error in errors if error != WIPE_CANCELLED]
        assert not errors, errors

    def landed(recorder, scene, after, timeout):
        """Seconds from `after` to the first of 8 consecutive moving frames of `scene`."""
        deadline = after + timeout
        while time.monotonic() < deadline + 0.2:
            frames = recorder.since(after)
            for start in range(len(frames) - 7):
                window = frames[start:start + 8]
                if all(f[1] == scene for f in window) and len({f[2] for f in window}) >= 6:
                    return frames[start][0] - after
            time.sleep(0.05)
        seen = [f[1] for f in recorder.since(after)][-20:]
        raise AssertionError((f'{scene} did not land within {timeout} s', seen))

    def assert_moving(frames, what):
        run = longest_still_run([f[3] for f in frames])
        assert run <= 2, (f'{what}: program froze for {run} frames', run)

    def assert_absent(frames, scene, what):
        shown = [f[0] for f in frames if f[1] == scene]
        assert not shown, (f'{what}: {scene} returned after the command', len(shown))

    def wait_idle(scene, timeout=1.0):
        """The take completes at the transition's last frame, a little after the picture reads as
        the destination."""
        deadline = time.monotonic() + timeout
        while True:
            s = status()
            if s['transition'] == 'idle' and s['pgm_scene'] == scene and not s['transition_paused']:
                return s
            assert time.monotonic() < deadline, ('take did not complete', s)
            time.sleep(0.02)

    endpoints = {}

    def settle(scene):
        t = take('cut', scene)
        landed(rec, scene, t, 1.0)
        time.sleep(0.2)
        s = status()
        assert s['transition'] == 'idle' and s['pgm_scene'] == scene, s
        endpoints[scene] = rec.latest

    def wait_partial_wipe(after, phase):
        """Block until the wipe covers 25-75 % of the frame, measured against the endpoint that
        is visible on the `phase` side of its midpoint (full0 before, full1 after)."""
        endpoint = endpoints['full0' if phase == 'before' else 'full1'].astype(np.int16)
        deadline = after + wipe_seconds + 3
        while time.monotonic() < deadline:
            image = rec.latest
            if image is not None:
                equal = float(np.mean(np.abs(image.astype(np.int16) - endpoint) <= 1))
                if 0.25 < equal < 0.75:
                    return
            time.sleep(0.01)
        raise AssertionError(f'could not observe a partial wipe {phase} its midpoint')

    results = []

    def case(name, **facts):
        check_errors(allow_wipe_cancel=True)
        result = {'case': name, **facts}
        results.append(result)
        print(json.dumps(result), flush=True)

    mixer.define_scene('split', {
        'camera0': {'dst_w': 320, 'dst_h': 360},
        'camera1': {'dst_x': 320, 'dst_w': 320, 'dst_h': 360},
    })
    time.sleep(0.5)
    settle('full1')
    settle('full0')

    # 1. CUT completes the fade on air, to its own scene.
    take('fade', 'full1')
    time.sleep(0.5)
    t = take('cut', 'full1')
    latency = landed(rec, 'full1', t, LANDING_S)
    time.sleep(0.5)
    assert_absent(rec.since(t), 'full0', 'cut completes fade')
    assert_moving(rec.since(t), 'cut completes fade')
    assert status()['transition'] == 'idle'
    case('cut_completes_fade', landed_ms=round(latency * 1000))

    # 2. CUT to another scene during a fade: the preset changes, then the cut completes.
    settle('full0')
    take('fade', 'full1')
    time.sleep(0.5)
    t = take('cut', 'split')
    latency = landed(rec, 'split', t, LANDING_S + 0.2)
    time.sleep(0.5)
    assert_absent(rec.since(t), 'full0', 'cut to another scene during fade')
    assert_moving(rec.since(t), 'cut to another scene during fade')
    case('cut_to_other_scene_during_fade', landed_ms=round(latency * 1000))

    # 3. AUTO again pauses the fade, both sources moving; AUTO once more resumes it.
    settle('full0')
    take('fade', 'full1')
    time.sleep(0.45)
    t_pause = take('fade', 'full1')
    time.sleep(FADE + 0.3)   # past the fade's original end
    s = status()
    assert s['transition'] == 'crossfade' and s['transition_paused'], s
    held = rec.since(t_pause + 0.2)
    assert held and all(f[1] is None for f in held), 'paused fade showed an endpoint'
    assert_moving(held, 'paused fade')
    t_resume = take('fade', 'full1')
    latency = landed(rec, 'full1', t_resume, FADE + LANDING_S)
    wait_idle('full1')
    case('auto_pauses_and_resumes_fade', paused_frames=len(held), resumed_landed_ms=round(latency * 1000))

    # 4. CUT while paused completes.
    take('fade', 'full0')
    time.sleep(0.45)
    take('fade', 'full0')
    time.sleep(0.5)
    assert status()['transition_paused']
    t = take('cut', 'full0')
    latency = landed(rec, 'full0', t, LANDING_S)
    assert_moving(rec.since(t), 'cut while paused')
    case('cut_completes_paused_fade', landed_ms=round(latency * 1000))

    # 5. Fade to another scene during a fade: the preset changes and the running fade carries
    # on to it, ending when the first fade would have ended, not restarting.
    settle('full0')
    t_start = take('fade', 'full1')
    time.sleep(0.4)
    t = take('fade', 'split')
    latency = landed(rec, 'split', t_start, FADE + 0.6)
    assert_absent(rec.since(t), 'full0', 'fade to another scene during fade')
    assert_moving(rec.since(t), 'fade to another scene during fade')
    case('fade_to_other_scene_continues_fade', landed_from_first_ms=round(latency * 1000))

    # 6. Preview during a fade replaces the preset the same way.
    settle('full0')
    t_start = take('fade', 'full1')
    time.sleep(0.4)
    take('preview', 'split')
    latency = landed(rec, 'split', t_start, FADE + 0.6)
    case('preview_during_fade_replaces_preset', landed_from_first_ms=round(latency * 1000))

    # 7. A wipe pressed for the scene of the fade on air is a second AUTO: it pauses.
    settle('full0')
    take('fade', 'full1')
    time.sleep(0.45)
    take('wipe', 'full1')
    time.sleep(0.5)
    assert status()['transition_paused']
    t = take('cut', 'full1')
    latency = landed(rec, 'full1', t, LANDING_S)
    case('wipe_during_fade_same_scene_pauses', landed_ms=round(latency * 1000))

    # 8-11. During a wipe, both sides of its midpoint.
    for phase in ('before', 'after'):
        settle('full0')
        t0 = take('wipe', 'full1')
        wait_partial_wipe(t0, phase)
        t = take('cut', 'full1')
        latency = landed(rec, 'full1', t, LANDING_S + 0.1)
        assert_moving(rec.since(t), f'cut completes wipe {phase}')
        assert status()['transition'] == 'idle'
        case('cut_completes_wipe', phase=phase, landed_ms=round(latency * 1000))

        settle('full0')
        t0 = take('wipe', 'full1')
        wait_partial_wipe(t0, phase)
        t = take('cut', 'split')
        latency = landed(rec, 'split', t, LANDING_S + 0.3)
        assert_moving(rec.since(t), f'cut to another scene during wipe {phase}')
        case('cut_to_other_scene_during_wipe', phase=phase, landed_ms=round(latency * 1000))

        settle('full0')
        t0 = take('wipe', 'full1')
        wait_partial_wipe(t0, phase)
        take('fade', 'full1')
        assert not status()['transition_paused']
        latency = landed(rec, 'full1', t0, wipe_seconds + 1.0)
        case('fade_same_scene_during_wipe_ignored', phase=phase, landed_from_wipe_ms=round(latency * 1000))

        settle('full0')
        t0 = take('wipe', 'full1')
        wait_partial_wipe(t0, phase)
        t = take('fade', 'split')
        latency = landed(rec, 'split', t0, wipe_seconds + 1.0)
        assert_moving(rec.since(t), f'fade to another scene during wipe {phase}')
        case('fade_to_other_scene_during_wipe', phase=phase, landed_from_wipe_ms=round(latency * 1000))

    # 12. mixer.interrupt cuts back to the program, live, nothing retained.
    settle('full0')
    take('fade', 'full1')
    time.sleep(0.5)
    t = take('interrupt', None)
    latency = landed(rec, 'full0', t, LANDING_S)
    assert_moving(rec.since(t), 'interrupt')
    case('interrupt_cuts_back_to_program', landed_ms=round(latency * 1000))

    # 13. Cut spam: the last cut wins, program never freezes, timestamps never go back.
    rng = random.Random(spam_seed)
    scenes = ('full0', 'full1', 'split')
    settle('full0')
    t0 = time.monotonic()
    for _ in range(60):
        take('cut', rng.choice(scenes))
        time.sleep(rng.uniform(0.01, 0.12))
    t = take('cut', 'full1')
    latency = landed(rec, 'full1', t, LANDING_S + 0.2)
    assert_moving(rec.since(t0), 'cut spam')
    case('cut_spam', cuts=61, final_landed_ms=round(latency * 1000))

    # 14. Mixed spam of every take kind, then a final cut.
    settle('full0')
    kinds = ('cut', 'fade', 'fade', 'wipe', 'preview')
    t0 = time.monotonic()
    for _ in range(80):
        take(rng.choice(kinds), rng.choice(scenes), duration=rng.choice((0.3, 0.6, 1.2)))
        time.sleep(rng.uniform(0.05, 0.5))
    t = take('cut', 'full0')
    latency = landed(rec, 'full0', t, LANDING_S + 0.3)
    assert_moving(rec.since(t0), 'mixed spam')
    check_errors(allow_wipe_cancel=True)
    case('mixed_spam', takes=81, final_landed_ms=round(latency * 1000))
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('inputs', nargs=2)
    parser.add_argument('--wipe-file', required=True)
    parser.add_argument('--wipe-seconds', type=float, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--port', type=int, default=18781)
    parser.add_argument('--seed', type=int, default=1)
    args = parser.parse_args()
    from check_transition_recovery import recovery_graph
    with recovery_graph(args.inputs, port=args.port, control=True) as (avp, mixer, output, errors):
        with Recorder(output) as recorder:
            results = check(avp, mixer, recorder, errors, args.port, args.wipe_file, args.wipe_seconds, args.seed)
    args.output.write_text(json.dumps({'passed': results}, indent=2) + '\n')


if __name__ == '__main__':
    main()
